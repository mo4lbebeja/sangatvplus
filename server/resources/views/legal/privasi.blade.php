    <h1>Kebijakan Privasi SangaTV Plus</h1>
    <p class="muted">Berlaku sejak 15 November 2026 · Dikelola oleh Sijalucom Kreasi Mandiri</p>

    <p>SangaTV Plus adalah sistem TV hotel: aplikasi di TV kamar dan panel pengelola (CMS) untuk hotel. Halaman ini menjelaskan data apa yang diproses dan untuk apa.</p>

    <h2>Data yang diproses</h2>
    <ul>
        <li><b>Data tamu</b> dari hotel atau sistem PMS-nya: sapaan, nama, nomor kamar, bahasa, waktu check-in/check-out — untuk menampilkan sapaan di TV kamar.</li>
        <li><b>Data TV</b>: model, versi aplikasi, status menyala/standby, alamat IP — untuk pemantauan dan perbaikan.</li>
        <li><b>Statistik tontonan</b>: channel dan lamanya ditonton, per kamar, tanpa nama tamu.</li>
        <li><b>Akun staf hotel</b>: nama, email, peran, dan log aktivitas di CMS.</li>
    </ul>

    <h2>Yang tidak kami lakukan</h2>
    <ul>
        <li>Tidak membaca isi layar, akun streaming, atau aplikasi lain yang dipakai tamu.</li>
        <li>Tidak menjual atau membagikan data kepada pihak lain di luar hotel yang bersangkutan.</li>
    </ul>

    <h2>Penyimpanan dan keamanan</h2>
    <ul>
        <li>Data disimpan di server SangaTV Plus; komunikasi TV ke server memakai HTTPS.</li>
        <li>Data tamu yang sudah check-out dianonimkan otomatis setelah 90 hari.</li>
        <li>Cadangan (backup) database dienkripsi AES-256 sebelum disalin ke penyimpanan cadangan milik pengelola (termasuk Google Drive). Akses Google Drive aplikasi ini hanya ke berkas yang dibuatnya sendiri.</li>
    </ul>

    <h2>Hak Anda</h2>
    <p>Tamu dapat meminta hotel untuk melihat, memperbaiki, atau menghapus datanya. Hotel dapat mengekspor seluruh datanya dari CMS kapan saja.</p>

